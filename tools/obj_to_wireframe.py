#!/usr/bin/env python3
"""Convert OBJ polygon boundaries/lines to centered Rust wireframe geometry (stdlib only).

No triangulation: a quad stays four edges. Shared edges are emitted once. Materials,
normals and texture coordinates are unnecessary for monochrome wireframe rendering.
"""
import argparse
import math
from pathlib import Path


def convert(source, source_name="OBJ input"):
    vertices, edges = [], set()
    for number, line in enumerate(source.splitlines(), 1):
        words = line.split('#', 1)[0].split()
        if not words:
            continue
        if words[0] == 'v':
            if len(words) != 4:
                raise ValueError(f'line {number}: expected three vertex coordinates')
            vertex = tuple(map(float, words[1:]))
            if not all(map(math.isfinite, vertex)):
                raise ValueError(f'line {number}: non-finite vertex')
            vertices.append(vertex)
        elif words[0] in ('f', 'l'):
            indices = []
            for token in words[1:]:
                value = int(token.split('/')[0])
                index = value - 1 if value > 0 else len(vertices) + value
                if value == 0 or not 0 <= index < len(vertices):
                    raise ValueError(f'line {number}: invalid vertex index {value}')
                indices.append(index)
            if len(indices) < (3 if words[0] == 'f' else 2):
                raise ValueError(f'line {number}: too few vertices')
            pairs = list(zip(indices, indices[1:]))
            if words[0] == 'f':
                pairs.append((indices[-1], indices[0]))
            for a, b in pairs:
                if vertices[a] == vertices[b]:
                    raise ValueError(f'line {number}: zero-length edge')
                edges.add(tuple(sorted((a, b))))
    if not edges:
        raise ValueError('OBJ contains no polygon edges or lines')
    used = sorted({i for edge in edges for i in edge})
    center = [(min(vertices[i][a] for i in used) + max(vertices[i][a] for i in used)) / 2 for a in range(3)]
    centered = [tuple(vertices[i][a] - center[a] for a in range(3)) for i in used]
    radius = max(math.sqrt(sum(x*x for x in v)) for v in centered)
    points = [tuple(x * 4 / radius for x in v) for v in centered]
    remap = {old: new for new, old in enumerate(used)}
    lines = ['// Generated by tools/obj_to_wireframe.py; do not edit.',
             f'// Source: {source_name}. Original orientation retained.',
             'pub(super) fn model() -> super::Model {',
             '    const VERTICES: &[[f32; 3]] = &[']
    lines += ['        [' + ', '.join(str(round(x, 6)) for x in v) + '],' for v in points]
    lines += ['    ];', '    const EDGES: &[(usize, usize)] = &[']
    lines += [f'        ({remap[a]}, {remap[b]}),' for a, b in sorted(edges)]
    lines += ['    ];', '    super::Model {',
              '        segs: EDGES.iter().map(|&(a, b)| super::Seg {',
              '            a: VERTICES[a], b: VERTICES[b], major: true,',
              '        }).collect(),', '        zoom: 1.0,', '    }', '}']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(convert(args.source.read_text(), args.source.as_posix()))
